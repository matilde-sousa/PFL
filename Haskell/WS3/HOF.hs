-- 3.9
divisors :: Integer -> [Integer]
divisors n = filter (\d -> n `mod` d == 0) [1..n]

-- 3.10
intSqrRoot :: Integer -> Integer
intSqrRoot n = floor (sqrt (fromIntegral n))

isPrimeFast :: Integer -> Bool
isPrimeFast n = n > 1 && all(\d -> n `mod` d /= 0) [2..intSqrRoot(n)]

