-- a)
intercalate :: a -> [a] -> [[a]]
intercalate n [] = [[n]]
-- Possibility A: The new element 'n' is placed at the front of the whole list.
-- Possibility B: The new element 'n' is inserted into ALL positions of the tail 'xs'.
-- We prepend the current head 'x' to every list generated by the recursive call.
intercalate n (x : xs) = (n : x : xs) :  map(\ ys -> x : ys) (intercalate n xs)

-- b)

permutations :: [a] -> [[a]]
permutations [] = [[]]
permutations (x : xs) = concatMap (intercalate x) (permutations xs)